import pandas as pd
import re

class GlobalDataSanitizer:
    def __init__(self, df):
        # Warning se bachne ke liye copy() ka istemal kiya hai
        self.df = df.copy()

    def sanitize_currencies(self, column_name):
        if column_name in self.df.columns:
            cleaned_col = self.df[column_name].astype(str).apply(
                lambda x: re.sub(r'[^\d.]', '', x) if x != 'nan' else x
            )
            cleaned_col = pd.to_numeric(cleaned_col, errors='coerce')
            # Pandas warning khatam karne ke liye .loc ka use
            self.df.loc[:, column_name] = cleaned_col
            print(f"✔ Currency column '{column_name}' sanitized successfully.")

    def standardize_dates(self, column_name):
        if column_name in self.df.columns:
            formatted_dates = pd.to_datetime(self.df[column_name], errors='coerce').dt.strftime('%Y-%m-%d')
            self.df.loc[:, column_name] = formatted_dates
            print(f"✔ Date column '{column_name}' standardized to YYYY-MM-DD.")

    def remove_duplicates_and_spaces(self):
        initial_rows = len(self.df)
        self.df = self.df.drop_duplicates().copy()

        for col in self.df.select_dtypes(include=['object']).columns:
            cleaned_text = self.df[col].str.strip().str.replace(r'\s+', ' ', regex=True)
            self.df.loc[:, col] = cleaned_text

        print(f"✔ Removed {initial_rows - len(self.df)} duplicate rows and cleaned whitespaces.")

# --- LIVE TEST WITH DUMMY DATA ---
data = {
    'Name': ['  Ali Khan  ', 'Sara Ahmed', '  Ali Khan  ', 'John Doe'],
    'Joining_Date': ['12/15/2023', '2023-10-05', '12/15/2023', 'invalid_date'],
    'Salary': ['$5,000 USD', '€4500', '$5,000 USD', 'Not Given']
}

messy_df = pd.DataFrame(data)
print("--- ORIGINAL MESSY DATA ---")
print(messy_df)
print("\n" + "="*40 + "\n")

sanitizer = GlobalDataSanitizer(messy_df)
sanitizer.remove_duplicates_and_spaces()
sanitizer.standardize_dates('Joining_Date')
sanitizer.sanitize_currencies('Salary')

print("\n" + "="*40 + "\n")
print("--- 100% CLEANED GLOBAL OUTPUT DATA (WITHOUT WARNINGS) ---")
print(sanitizer.df)

